/**
 * Transform book data for frontend
 */
function transformBook(book) {
  let samplePages = book.samplePages || book.sample_pages || [];
  if (typeof samplePages === "string") {
    try {
      samplePages = JSON.parse(samplePages);
    } catch (e) {
      samplePages = [];
    }
  }

  let galleryPhotos = book.galleryPhotos || book.gallery_photos || [];
  if (typeof galleryPhotos === "string") {
    try {
      galleryPhotos = JSON.parse(galleryPhotos);
    } catch (e) {
      galleryPhotos = [];
    }
  }

  // Construct direct purchase link (e.g., Amazon link by ISBN or fallback)
  const isbnClean = book.isbn ? book.isbn.replace(/[^a-zA-Z0-9]/g, "") : "";
  const buyUrl = isbnClean
    ? `https://www.amazon.com/dp/${isbnClean}`
    : "mailto:geral@escritoresnogueira.com?subject=Compra%20do%20Livro";

  return {
    id: book.id,
    slug: book.slug,
    title: book.title,
    author: book.author,
    category: book.category || "geral",
    price: parseFloat(book.price) || 0,
    oldPrice: book.original_price || book.oldPrice ? parseFloat(book.original_price || book.oldPrice) : null,
    originalPrice: book.original_price ? parseFloat(book.original_price) : null,
    description: book.description || "",
    isbn: book.isbn || "",
    pages: book.pages || 0,
    year: book.publish_year || book.year || null,
    language: book.language || "Português",
    publisher: book.publisher || "Escritores Nogueira",
    featured: book.featured || false,
    promo: book.promo || false,
    image: book.cover_image || book.cover_url || book.image || null,
    stock: book.stock || 0,
    rating: book.rating || 0,
    reviewCount: book.review_count || book.reviewCount || 0,
    samplePages: samplePages,
    videoHorizontalUrl: book.video_horizontal_url || book.videoHorizontalUrl || null,
    videoVerticalUrl: book.video_vertical_url || book.videoVerticalUrl || null,
    galleryPhotos: galleryPhotos,
    buyUrl: buyUrl,
  };
}

/**
 * Transform blog post data for frontend
 */
function transformBlogPost(post) {
  return {
    id: post.id,
    slug: post.slug,
    title: post.title,
    author: post.author || "Escritores Nogueira",
    category: post.category_name || post.category || "Notícias",
    date: post.created_at || post.date,
    excerpt: post.excerpt || "",
    content: post.content || "",
    image: post.featured_image || post.image || null,
    readTime: "5 min de leitura",
    featured: post.featured || false,
  };
}

/**
 * Transform array of books
 */
function transformBooks(books) {
  return books.map(transformBook);
}

